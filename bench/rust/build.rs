//! Build script: generates Rust test functions from bench/tests.json.
//!
//! This makes tests.json the single source of truth for test definitions.
//! Adding a test to tests.json automatically creates a corresponding #[test] fn.

use serde::Deserialize;
use std::fmt::Write as FmtWrite;
use std::fs;
use std::path::Path;

#[derive(Deserialize)]
struct TestEntry {
    name: String,
    level: u32,
    fixture: String,
    kind: String,
    #[serde(default)]
    expected: Option<String>,
    #[serde(default)]
    expected_output: Option<String>,
    #[serde(default)]
    deprecated_after: Option<u32>,
}

fn generate() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let tests_json_path = Path::new(&manifest_dir).join("../tests.json");
    let out_dir = std::env::var("OUT_DIR")?;
    let out_path = Path::new(&out_dir).join("tests_generated.rs");

    // Tell cargo to rerun if tests.json changes
    println!("cargo:rerun-if-changed=../tests.json");
    // Also rerun if any fixture changes
    println!("cargo:rerun-if-changed=../fixtures");

    let json = fs::read_to_string(&tests_json_path)?;
    let tests: Vec<TestEntry> = serde_json::from_str(&json)?;

    let mut out = String::new();

    let level_count = {
        let mut levels: Vec<u32> = tests.iter().map(|t| t.level).collect();
        levels.sort();
        levels.dedup();
        levels.len()
    };
    writeln!(out, "// AUTO-GENERATED by build.rs from tests.json — do not edit")?;
    writeln!(out, "// {count} tests across {level_count} levels", count = tests.len())?;
    writeln!(out)?;
    writeln!(out, "use crate::scheme::eval_str;")?;
    writeln!(out)?;

    // Check if any test uses eval_str_with_output
    let needs_output = tests.iter().any(|t| t.kind == "eval_str_with_output");
    if needs_output {
        writeln!(out, "#[allow(unused_imports)]")?;
        writeln!(out, "use crate::scheme::eval_str_with_output;")?;
        writeln!(out)?;
    }

    // Helper function for position checking (used by eval_str_err_with_position)
    let needs_position = tests.iter().any(|t| t.kind == "eval_str_err_with_position");
    if needs_position {
        writeln!(out, "fn has_position_info(msg: &str) -> bool {{")?;
        writeln!(out, "    msg.as_bytes().windows(2).any(|w| w[0].is_ascii_digit() && w[1] == b':')")?;
        writeln!(out, "}}")?;
        writeln!(out)?;
    }

    // Helper for deprecated level checking
    let needs_deprecated = tests.iter().any(|t| t.deprecated_after.is_some());
    if needs_deprecated {
        writeln!(out, "fn current_bench_level() -> u32 {{")?;
        writeln!(out, "    std::env::var(\"BENCH_LEVEL\").ok().and_then(|v| v.parse().ok()).unwrap_or(u32::MAX)")?;
        writeln!(out, "}}")?;
        writeln!(out)?;
    }

    // Compute absolute path to fixtures dir for include_str!()
    let fixtures_abs = Path::new(&manifest_dir)
        .join("../fixtures")
        .canonicalize()?;

    // Generate one #[test] fn per entry
    for test in &tests {
        let fn_name = test.name.replace('-', "_");
        let fixture_path = fixtures_abs.join(&test.fixture);
        let fixture_path_str = fixture_path.display();

        writeln!(out, "#[test]")?;
        writeln!(out, "fn test_{fn_name}() {{")?;

        // Deprecated check
        if let Some(after) = test.deprecated_after {
            writeln!(out, "    if current_bench_level() > {after} {{ return; }}")?;
        }

        match test.kind.as_str() {
            "eval_str_ok" => {
                let expected = test.expected.as_deref().unwrap_or("");
                let escaped = expected.replace('\\', "\\\\").replace('"', "\\\"");
                writeln!(out, "    assert_eq!(")?;
                writeln!(out, "        eval_str(include_str!(\"{fixture_path_str}\").trim()),")?;
                writeln!(out, "        Ok(\"{escaped}\".into())")?;
                writeln!(out, "    );")?;
            }
            "eval_str_err" => {
                writeln!(out, "    assert!(")?;
                writeln!(out, "        eval_str(include_str!(\"{fixture_path_str}\").trim()).is_err(),")?;
                writeln!(out, "        \"expected error for {}\"", test.name)?;
                writeln!(out, "    );")?;
            }
            "eval_str_err_with_position" => {
                writeln!(out, "    let err = eval_str(include_str!(\"{fixture_path_str}\").trim()).unwrap_err();")?;
                writeln!(out, "    assert!(")?;
                writeln!(out, "        has_position_info(&err.to_string()),")?;
                writeln!(out, "        \"error should contain position info: {{err}}\"")?;
                writeln!(out, "    );")?;
            }
            "eval_str_with_output" => {
                let expected_output = test.expected_output.as_deref().unwrap_or("");
                let escaped = expected_output.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n");
                writeln!(out, "    let (_, output) = eval_str_with_output(include_str!(\"{fixture_path_str}\").trim()).unwrap();")?;
                writeln!(out, "    assert_eq!(output, \"{escaped}\");")?;
            }
            other => {
                writeln!(out, "    // Unknown test kind: {other}")?;
                writeln!(out, "    unimplemented!(\"test kind '{}' not supported\");", other)?;
            }
        }

        writeln!(out, "}}")?;
        writeln!(out)?;
    }

    fs::write(&out_path, out)?;
    Ok(())
}

fn main() {
    generate().unwrap_or_else(|e| panic!("build.rs failed: {e}"));
}
