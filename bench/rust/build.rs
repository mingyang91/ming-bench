// Build script: generates Rust test functions from bench/tests.json.
// This makes tests.json the single source of truth for test definitions.
// Adding a test to tests.json automatically creates a corresponding #[test] fn.

use serde::Deserialize;
use std::collections::BTreeSet;
use std::error::Error;
use std::fs::{self, File};
use std::io::{self, BufWriter, Write};
use std::path::{Path, PathBuf};

type BuildResult<T> = Result<T, Box<dyn Error>>;

#[derive(Deserialize)]
struct TestEntry {
    name: String,
    level: u32,
    fixture: String,
    kind: String,
    #[serde(default)]
    expected: Option<String>,
    #[serde(default)]
    expected_output: Option<String>,
    #[serde(default)]
    deprecated_after: Option<u32>,
}

fn main() -> BuildResult<()> {
    println!("cargo:rerun-if-changed=../tests.json");
    println!("cargo:rerun-if-changed=../fixtures");

    let manifest_dir = manifest_dir()?;
    let tests = load_tests(&manifest_dir.join("../tests.json"))?;
    let fixtures_dir = resolve_fixtures_dir(&manifest_dir)?;
    let out_path = output_path()?;
    let output =
        File::create(&out_path).map_err(|error| contextual_io_error(&out_path, "create", error))?;
    let mut out = BufWriter::new(output);

    emit_header(&mut out, &tests)?;
    emit_support_code(&mut out, &tests)?;
    emit_tests(&mut out, &tests, &fixtures_dir)?;
    out.flush()?;

    Ok(())
}

fn manifest_dir() -> BuildResult<PathBuf> {
    Ok(PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?))
}

fn output_path() -> BuildResult<PathBuf> {
    let out_dir = PathBuf::from(std::env::var("OUT_DIR")?);
    Ok(out_dir.join("tests_generated.rs"))
}

fn load_tests(path: &Path) -> BuildResult<Vec<TestEntry>> {
    let json =
        fs::read_to_string(path).map_err(|error| contextual_io_error(path, "read", error))?;
    let tests = serde_json::from_str(&json)
        .map_err(|error| invalid_data_error(format!("cannot parse {}: {error}", path.display())))?;
    Ok(tests)
}

fn resolve_fixtures_dir(manifest_dir: &Path) -> BuildResult<PathBuf> {
    let fixtures_dir = manifest_dir.join("../fixtures");
    fixtures_dir
        .canonicalize()
        .map_err(|error| contextual_io_error(&fixtures_dir, "resolve", error).into())
}

fn emit_header(out: &mut impl Write, tests: &[TestEntry]) -> BuildResult<()> {
    writeln!(
        out,
        "// AUTO-GENERATED by build.rs from tests.json - do not edit"
    )?;
    writeln!(
        out,
        "// {} tests across {} levels",
        tests.len(),
        unique_level_count(tests)
    )?;
    writeln!(out)?;
    writeln!(out, "use crate::scheme::eval_str;")?;
    writeln!(out)?;
    Ok(())
}

fn emit_support_code(out: &mut impl Write, tests: &[TestEntry]) -> BuildResult<()> {
    if tests.iter().any(|test| test.kind == "eval_str_with_output") {
        emit_output_import(out)?;
    }

    if tests
        .iter()
        .any(|test| test.kind == "eval_str_err_with_position")
    {
        emit_position_helper(out)?;
    }

    if tests.iter().any(|test| test.deprecated_after.is_some()) {
        emit_deprecated_helper(out)?;
    }

    Ok(())
}

fn emit_output_import(out: &mut impl Write) -> BuildResult<()> {
    writeln!(out, "#[allow(unused_imports)]")?;
    writeln!(out, "use crate::scheme::eval_str_with_output;")?;
    writeln!(out)?;
    Ok(())
}

fn emit_position_helper(out: &mut impl Write) -> BuildResult<()> {
    writeln!(out, "fn has_position_info(msg: &str) -> bool {{")?;
    writeln!(
        out,
        "    msg.as_bytes().windows(2).any(|w| w[0].is_ascii_digit() && w[1] == b':')"
    )?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    Ok(())
}

fn emit_deprecated_helper(out: &mut impl Write) -> BuildResult<()> {
    writeln!(out, "fn current_bench_level() -> u32 {{")?;
    writeln!(out, "    match std::env::var(\"BENCH_LEVEL\") {{")?;
    writeln!(
        out,
        "        Ok(level) => level.parse().unwrap_or(u32::MAX),"
    )?;
    writeln!(out, "        Err(_) => u32::MAX,")?;
    writeln!(out, "    }}")?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    Ok(())
}

fn emit_tests(out: &mut impl Write, tests: &[TestEntry], fixtures_dir: &Path) -> BuildResult<()> {
    for test in tests {
        emit_test(out, test, fixtures_dir)?;
    }

    Ok(())
}

fn emit_test(out: &mut impl Write, test: &TestEntry, fixtures_dir: &Path) -> BuildResult<()> {
    let function_name = sanitize_test_name(&test.name);
    let fixture_path = fixtures_dir.join(&test.fixture);
    let fixture_literal = escape_rust_string(&fixture_path.to_string_lossy());

    writeln!(out, "#[test]")?;
    writeln!(out, "fn test_{function_name}() {{")?;

    if let Some(after) = test.deprecated_after {
        writeln!(out, "    if current_bench_level() > {after} {{ return; }}")?;
    }

    match test.kind.as_str() {
        "eval_str_ok" => emit_eval_str_ok_body(
            out,
            &fixture_literal,
            test.expected.as_deref().unwrap_or(""),
        )?,
        "eval_str_err" => emit_eval_str_err_body(out, &fixture_literal, &test.name)?,
        "eval_str_err_with_position" => {
            emit_eval_str_err_with_position_body(out, &fixture_literal)?
        }
        "eval_str_with_output" => emit_eval_str_with_output_body(
            out,
            &fixture_literal,
            test.expected_output.as_deref().unwrap_or(""),
        )?,
        other => return Err(invalid_data_error(format!("unsupported test kind: {other}")).into()),
    }

    writeln!(out, "}}")?;
    writeln!(out)?;
    Ok(())
}

fn emit_eval_str_ok_body(
    out: &mut impl Write,
    fixture_literal: &str,
    expected: &str,
) -> BuildResult<()> {
    writeln!(out, "    assert_eq!(")?;
    writeln!(
        out,
        "        eval_str(include_str!(\"{fixture_literal}\").trim()),"
    )?;
    writeln!(
        out,
        "        Ok(\"{}\".into())",
        escape_rust_string(expected)
    )?;
    writeln!(out, "    );")?;
    Ok(())
}

fn emit_eval_str_err_body(
    out: &mut impl Write,
    fixture_literal: &str,
    test_name: &str,
) -> BuildResult<()> {
    writeln!(out, "    assert!(")?;
    writeln!(
        out,
        "        eval_str(include_str!(\"{fixture_literal}\").trim()).is_err(),"
    )?;
    writeln!(
        out,
        "        \"expected error for {}\"",
        escape_rust_string(test_name)
    )?;
    writeln!(out, "    );")?;
    Ok(())
}

fn emit_eval_str_err_with_position_body(
    out: &mut impl Write,
    fixture_literal: &str,
) -> BuildResult<()> {
    writeln!(
        out,
        "    let err = eval_str(include_str!(\"{fixture_literal}\").trim())"
    )?;
    writeln!(
        out,
        "        .expect_err(\"fixture should fail with position information\");"
    )?;
    writeln!(out, "    assert!(")?;
    writeln!(out, "        has_position_info(&err.to_string()),")?;
    writeln!(
        out,
        "        \"error should contain position info: {{err}}\""
    )?;
    writeln!(out, "    );")?;
    Ok(())
}

fn emit_eval_str_with_output_body(
    out: &mut impl Write,
    fixture_literal: &str,
    expected_output: &str,
) -> BuildResult<()> {
    writeln!(
        out,
        "    let (_, output) = eval_str_with_output(include_str!(\"{fixture_literal}\").trim())"
    )?;
    writeln!(
        out,
        "        .expect(\"fixture should evaluate successfully\");"
    )?;
    writeln!(
        out,
        "    assert_eq!(output, \"{}\");",
        escape_rust_string(expected_output)
    )?;
    Ok(())
}

fn unique_level_count(tests: &[TestEntry]) -> usize {
    tests
        .iter()
        .map(|test| test.level)
        .collect::<BTreeSet<_>>()
        .len()
}

fn sanitize_test_name(name: &str) -> String {
    name.chars()
        .map(|character| match character {
            '0'..='9' | 'A'..='Z' | 'a'..='z' => character,
            _ => '_',
        })
        .collect()
}

fn escape_rust_string(value: &str) -> String {
    value.chars().flat_map(char::escape_default).collect()
}

fn contextual_io_error(path: &Path, action: &str, error: io::Error) -> io::Error {
    io::Error::new(
        error.kind(),
        format!("cannot {action} {}: {error}", path.display()),
    )
}

fn invalid_data_error(message: String) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, message)
}
