/// Build script: generates Rust test functions from bench/tests.json.
///
/// This makes tests.json the single source of truth for test definitions.
/// Adding a test to tests.json automatically creates a corresponding #[test] fn.

use serde::Deserialize;
use std::fs;
use std::io::Write;
use std::path::Path;
use std::process::Command;

#[derive(Deserialize)]
struct TestEntry {
    name: String,
    level: u32,
    fixture: String,
    kind: String,
    #[serde(default)]
    expected: Option<String>,
    #[serde(default)]
    expected_output: Option<String>,
    #[serde(default)]
    deprecated_after: Option<u32>,
}

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let tests_json_path = Path::new(&manifest_dir).join("../tests.json");
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let out_dir = Path::new(&out_dir);
    let out_path = out_dir.join("tests_generated.rs");

    // Tell cargo to rerun if tests.json changes
    println!("cargo:rerun-if-changed=../tests.json");
    // Also rerun if any fixture changes
    println!("cargo:rerun-if-changed=../fixtures");

    let json = fs::read_to_string(&tests_json_path)
        .unwrap_or_else(|e| panic!("Cannot read {}: {e}", tests_json_path.display()));
    let tests: Vec<TestEntry> =
        serde_json::from_str(&json).unwrap_or_else(|e| panic!("Cannot parse tests.json: {e}"));

    let mut out = fs::File::create(&out_path)
        .unwrap_or_else(|e| panic!("Cannot create {}: {e}", out_path.display()));

    writeln!(out, "// AUTO-GENERATED by build.rs from tests.json — do not edit").unwrap();
    writeln!(out, "// {} tests across {} levels", tests.len(), {
        let mut levels: Vec<u32> = tests.iter().map(|t| t.level).collect();
        levels.sort();
        levels.dedup();
        levels.len()
    }).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use crate::scheme::eval_str;").unwrap();
    writeln!(out).unwrap();

    // Check if any test uses eval_str_with_output
    let needs_output = tests.iter().any(|t| t.kind == "eval_str_with_output");
    if needs_output {
        writeln!(out, "#[allow(unused_imports)]").unwrap();
        writeln!(out, "use crate::scheme::eval_str_with_output;").unwrap();
        writeln!(out).unwrap();
    }

    // Helper function for position checking (used by eval_str_err_with_position)
    let needs_position = tests.iter().any(|t| t.kind == "eval_str_err_with_position");
    if needs_position {
        writeln!(out, "fn has_position_info(msg: &str) -> bool {{").unwrap();
        writeln!(out, "    msg.as_bytes().windows(2).any(|w| w[0].is_ascii_digit() && w[1] == b':')").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    // Helper for deprecated level checking
    let needs_deprecated = tests.iter().any(|t| t.deprecated_after.is_some());
    if needs_deprecated {
        writeln!(out, "fn current_bench_level() -> u32 {{").unwrap();
        writeln!(out, "    std::env::var(\"BENCH_LEVEL\").ok().and_then(|v| v.parse().ok()).unwrap_or(u32::MAX)").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    // Compute absolute path to fixtures dir for include_str!()
    let fixtures_abs = Path::new(&manifest_dir)
        .join("../fixtures")
        .canonicalize()
        .unwrap_or_else(|e| panic!("Cannot resolve fixtures dir: {e}"));

    // Generate one #[test] fn per entry
    for test in &tests {
        let fn_name = test.name.replace('-', "_");
        let fixture_path = fixtures_abs.join(&test.fixture);
        let fixture_path_str = fixture_path.display();

        writeln!(out, "#[test]").unwrap();
        writeln!(out, "fn test_{fn_name}() {{").unwrap();

        // Deprecated check
        if let Some(after) = test.deprecated_after {
            writeln!(out, "    if current_bench_level() > {after} {{ return; }}").unwrap();
        }

        match test.kind.as_str() {
            "eval_str_ok" => {
                let expected = test.expected.as_deref().unwrap_or("");
                let escaped = expected.replace('\\', "\\\\").replace('"', "\\\"");
                writeln!(out, "    assert_eq!(").unwrap();
                writeln!(out, "        eval_str(include_str!(\"{fixture_path_str}\").trim()),").unwrap();
                writeln!(out, "        Ok(\"{escaped}\".into())").unwrap();
                writeln!(out, "    );").unwrap();
            }
            "eval_str_err" => {
                writeln!(out, "    assert!(").unwrap();
                writeln!(out, "        eval_str(include_str!(\"{fixture_path_str}\").trim()).is_err(),").unwrap();
                writeln!(out, "        \"expected error for {}\"", test.name).unwrap();
                writeln!(out, "    );").unwrap();
            }
            "eval_str_err_with_position" => {
                writeln!(out, "    let err = eval_str(include_str!(\"{fixture_path_str}\").trim()).unwrap_err();").unwrap();
                writeln!(out, "    assert!(").unwrap();
                writeln!(out, "        has_position_info(&err.to_string()),").unwrap();
                writeln!(out, "        \"error should contain position info: {{err}}\"").unwrap();
                writeln!(out, "    );").unwrap();
            }
            "eval_str_with_output" => {
                let expected_output = test.expected_output.as_deref().unwrap_or("");
                let escaped = expected_output.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n");
                writeln!(out, "    let (_, output) = eval_str_with_output(include_str!(\"{fixture_path_str}\").trim()).unwrap();").unwrap();
                writeln!(out, "    assert_eq!(output, \"{escaped}\");").unwrap();
            }
            other => {
                writeln!(out, "    // Unknown test kind: {other}").unwrap();
                writeln!(out, "    unimplemented!(\"test kind '{}' not supported\");", other).unwrap();
            }
        }

        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    build_go_bridge(&manifest_dir, out_dir);
}

fn build_go_bridge(manifest_dir: &str, out_dir: &Path) {
    let go_dir = Path::new(manifest_dir)
        .join("../go")
        .canonicalize()
        .unwrap_or_else(|e| panic!("Cannot resolve Go source dir: {e}"));

    emit_go_rerun_directives(&go_dir);

    let bridge_dir = out_dir.join("go_bridge");
    fs::create_dir_all(&bridge_dir)
        .unwrap_or_else(|e| panic!("Cannot create {}: {e}", bridge_dir.display()));

    let go_mod_path = bridge_dir.join("go.mod");
    let main_go_path = bridge_dir.join("main.go");
    let bridge_bin_path = bridge_dir.join("ming_go_bridge");

    fs::write(&go_mod_path, GO_BRIDGE_GO_MOD)
        .unwrap_or_else(|e| panic!("Cannot write {}: {e}", go_mod_path.display()));
    fs::write(&main_go_path, GO_BRIDGE_MAIN)
        .unwrap_or_else(|e| panic!("Cannot write {}: {e}", main_go_path.display()));

    let bridge_mount = format!("{}:/bridge:Z", bridge_dir.display());
    let go_mount = format!("{}:/ming:ro,Z", go_dir.display());
    let build_cmd =
        "CGO_ENABLED=0 /usr/local/go/bin/go build -trimpath -ldflags='-s -w' -o /bridge/ming_go_bridge .";

    let status = Command::new("sudo")
        .args([
            "podman",
            "run",
            "--rm",
            "-v",
            &bridge_mount,
            "-v",
            &go_mount,
            "-w",
            "/bridge",
            "docker.io/library/golang:1.23",
            "bash",
            "-lc",
            build_cmd,
        ])
        .status()
        .unwrap_or_else(|e| panic!("Failed to start Go bridge build: {e}"));

    if !status.success() {
        panic!("Go bridge build failed with status {status}");
    }

    println!(
        "cargo:rustc-env=MING_GO_BRIDGE_BIN={}",
        bridge_bin_path.display()
    );
}

fn emit_go_rerun_directives(go_dir: &Path) {
    let entries = fs::read_dir(go_dir)
        .unwrap_or_else(|e| panic!("Cannot list {}: {e}", go_dir.display()));

    for entry in entries {
        let path = entry
            .unwrap_or_else(|e| panic!("Cannot read {} entry: {e}", go_dir.display()))
            .path();

        if path.extension().and_then(|ext| ext.to_str()) == Some("go")
            || path.file_name().and_then(|name| name.to_str()) == Some("go.mod")
        {
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
}

const GO_BRIDGE_GO_MOD: &str = r#"module rustbridge

go 1.23

require ming v0.0.0

replace ming => /ming
"#;

const GO_BRIDGE_MAIN: &str = r#"package main

import (
    "encoding/binary"
    "fmt"
    "io"
    "os"

    "ming"
)

func writeField(value string) error {
    var size [8]byte
    binary.BigEndian.PutUint64(size[:], uint64(len(value)))
    if _, err := os.Stdout.Write(size[:]); err != nil {
        return err
    }
    _, err := io.WriteString(os.Stdout, value)
    return err
}

func writeSuccess(fields ...string) error {
    if _, err := os.Stdout.Write([]byte{'S'}); err != nil {
        return err
    }
    for _, field := range fields {
        if err := writeField(field); err != nil {
            return err
        }
    }
    return nil
}

func writeError(err error) error {
    if _, writeErr := os.Stdout.Write([]byte{'E'}); writeErr != nil {
        return writeErr
    }
    return writeField(err.Error())
}

func main() {
    mode := "eval"
    if len(os.Args) > 1 {
        mode = os.Args[1]
    }

    input, err := io.ReadAll(os.Stdin)
    if err != nil {
        panic(err)
    }

    switch mode {
    case "eval":
        result, err := ming.EvalStr(string(input))
        if err != nil {
            if writeErr := writeError(err); writeErr != nil {
                panic(writeErr)
            }
            return
        }
        if err := writeSuccess(result); err != nil {
            panic(err)
        }
    case "eval-output":
        result, output, err := ming.EvalStrWithOutput(string(input))
        if err != nil {
            if writeErr := writeError(err); writeErr != nil {
                panic(writeErr)
            }
            return
        }
        if err := writeSuccess(result, output); err != nil {
            panic(err)
        }
    default:
        if err := writeError(fmt.Errorf("unknown mode: %s", mode)); err != nil {
            panic(err)
        }
    }
}
"#;
