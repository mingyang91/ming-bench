/// Build script: generates Rust test functions from bench/tests.json.
///
/// This makes tests.json the single source of truth for test definitions.
/// Adding a test to tests.json automatically creates a corresponding #[test] fn.
use serde::Deserialize;
use std::fs;
use std::io::{self, Write};
use std::path::{Path, PathBuf};

#[derive(Deserialize)]
struct TestEntry {
    name: String,
    level: u32,
    fixture: String,
    kind: String,
    #[serde(default)]
    expected: Option<String>,
    #[serde(default)]
    expected_output: Option<String>,
    #[serde(default)]
    deprecated_after: Option<u32>,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Tell cargo to rerun if tests.json changes
    println!("cargo:rerun-if-changed=../tests.json");
    // Also rerun if any fixture changes
    println!("cargo:rerun-if-changed=../fixtures");

    let manifest_dir = env_var("CARGO_MANIFEST_DIR")?;
    let tests_json_path = Path::new(&manifest_dir).join("../tests.json");
    let out_dir = env_var("OUT_DIR")?;
    let out_path = Path::new(&out_dir).join("tests_generated.rs");
    let fixtures_dir = canonicalize(&Path::new(&manifest_dir).join("../fixtures"))?;

    let tests = load_tests(&tests_json_path)?;
    let mut out = create_output(&out_path)?;
    write_generated_tests(&mut out, &tests, &fixtures_dir)?;

    Ok(())
}

fn env_var(name: &str) -> io::Result<String> {
    std::env::var(name).map_err(|error| {
        io::Error::other(format!("Cannot read environment variable {name}: {error}"))
    })
}

fn canonicalize(path: &Path) -> io::Result<PathBuf> {
    path.canonicalize()
        .map_err(|error| io::Error::other(format!("Cannot resolve {}: {error}", path.display())))
}

fn load_tests(path: &Path) -> Result<Vec<TestEntry>, Box<dyn std::error::Error>> {
    let json = fs::read_to_string(path)
        .map_err(|error| io::Error::other(format!("Cannot read {}: {error}", path.display())))?;

    let tests = serde_json::from_str(&json)
        .map_err(|error| io::Error::other(format!("Cannot parse tests.json: {error}")))?;

    Ok(tests)
}

fn create_output(path: &Path) -> io::Result<fs::File> {
    fs::File::create(path)
        .map_err(|error| io::Error::other(format!("Cannot create {}: {error}", path.display())))
}

fn write_generated_tests(
    out: &mut dyn Write,
    tests: &[TestEntry],
    fixtures_dir: &Path,
) -> io::Result<()> {
    write_header(out, tests)?;
    write_imports(out, tests)?;
    write_helpers(out, tests)?;

    for test in tests {
        write_test(out, test, fixtures_dir)?;
    }

    Ok(())
}

fn write_header(out: &mut dyn Write, tests: &[TestEntry]) -> io::Result<()> {
    writeln!(
        out,
        "// AUTO-GENERATED by build.rs from tests.json — do not edit"
    )?;
    writeln!(
        out,
        "// {} tests across {} levels",
        tests.len(),
        level_count(tests)
    )?;
    writeln!(out)?;

    Ok(())
}

fn level_count(tests: &[TestEntry]) -> usize {
    let mut levels: Vec<u32> = tests.iter().map(|test| test.level).collect();
    levels.sort();
    levels.dedup();
    levels.len()
}

fn write_imports(out: &mut dyn Write, tests: &[TestEntry]) -> io::Result<()> {
    writeln!(out, "use crate::scheme::eval_str;")?;
    writeln!(out)?;

    if tests.iter().any(|test| test.kind == "eval_str_with_output") {
        writeln!(out, "#[allow(unused_imports)]")?;
        writeln!(out, "use crate::scheme::eval_str_with_output;")?;
        writeln!(out)?;
    }

    Ok(())
}

fn write_helpers(out: &mut dyn Write, tests: &[TestEntry]) -> io::Result<()> {
    if tests
        .iter()
        .any(|test| test.kind == "eval_str_err_with_position")
    {
        write_position_helper(out)?;
    }

    if tests.iter().any(|test| test.deprecated_after.is_some()) {
        write_deprecated_helper(out)?;
    }

    Ok(())
}

fn write_position_helper(out: &mut dyn Write) -> io::Result<()> {
    writeln!(out, "fn has_position_info(msg: &str) -> bool {{")?;
    writeln!(
        out,
        "    msg.as_bytes().windows(2).any(|w| w[0].is_ascii_digit() && w[1] == b':')"
    )?;
    writeln!(out, "}}")?;
    writeln!(out)?;

    Ok(())
}

fn write_deprecated_helper(out: &mut dyn Write) -> io::Result<()> {
    writeln!(out, "fn current_bench_level() -> u32 {{")?;
    writeln!(
        out,
        "    std::env::var(\"BENCH_LEVEL\").ok().and_then(|v| v.parse().ok()).unwrap_or(u32::MAX)"
    )?;
    writeln!(out, "}}")?;
    writeln!(out)?;

    Ok(())
}

fn write_test(out: &mut dyn Write, test: &TestEntry, fixtures_dir: &Path) -> io::Result<()> {
    let fn_name = test.name.replace('-', "_");
    let fixture_path = fixtures_dir.join(&test.fixture);
    let fixture_path_str = fixture_path.display().to_string();

    writeln!(out, "#[test]")?;
    writeln!(out, "fn test_{fn_name}() {{")?;

    if let Some(after) = test.deprecated_after {
        writeln!(out, "    if current_bench_level() > {after} {{ return; }}")?;
    }

    write_test_body(out, test, &fixture_path_str)?;
    writeln!(out, "}}")?;
    writeln!(out)?;

    Ok(())
}

fn write_test_body(out: &mut dyn Write, test: &TestEntry, fixture_path: &str) -> io::Result<()> {
    match test.kind.as_str() {
        "eval_str_ok" => write_eval_str_ok_test(out, test, fixture_path),
        "eval_str_err" => write_eval_str_err_test(out, test, fixture_path),
        "eval_str_err_with_position" => write_eval_str_err_with_position_test(out, fixture_path),
        "eval_str_with_output" => write_eval_str_with_output_test(out, test, fixture_path),
        other => write_unsupported_test_kind(out, other),
    }
}

fn write_eval_str_ok_test(
    out: &mut dyn Write,
    test: &TestEntry,
    fixture_path: &str,
) -> io::Result<()> {
    let expected = test.expected.as_deref().unwrap_or_default();
    let escaped = escape_string_literal(expected);

    writeln!(out, "    assert_eq!(")?;
    writeln!(
        out,
        "        eval_str(include_str!(\"{fixture_path}\").trim()),"
    )?;
    writeln!(out, "        Ok(\"{escaped}\".into())")?;
    writeln!(out, "    );")?;

    Ok(())
}

fn write_eval_str_err_test(
    out: &mut dyn Write,
    test: &TestEntry,
    fixture_path: &str,
) -> io::Result<()> {
    writeln!(out, "    assert!(")?;
    writeln!(
        out,
        "        eval_str(include_str!(\"{fixture_path}\").trim()).is_err(),"
    )?;
    writeln!(out, "        \"expected error for {}\"", test.name)?;
    writeln!(out, "    );")?;

    Ok(())
}

fn write_eval_str_err_with_position_test(
    out: &mut dyn Write,
    fixture_path: &str,
) -> io::Result<()> {
    writeln!(
        out,
        "    let err = eval_str(include_str!(\"{fixture_path}\").trim()).unwrap_err();"
    )?;
    writeln!(out, "    assert!(")?;
    writeln!(out, "        has_position_info(&err.to_string()),")?;
    writeln!(
        out,
        "        \"error should contain position info: {{err}}\""
    )?;
    writeln!(out, "    );")?;

    Ok(())
}

fn write_eval_str_with_output_test(
    out: &mut dyn Write,
    test: &TestEntry,
    fixture_path: &str,
) -> io::Result<()> {
    let expected_output = test.expected_output.as_deref().unwrap_or_default();
    let escaped = escape_string_literal(expected_output);

    writeln!(
        out,
        "    let (_, output) = eval_str_with_output(include_str!(\"{fixture_path}\").trim()).unwrap();"
    )?;
    writeln!(out, "    assert_eq!(output, \"{escaped}\");")?;

    Ok(())
}

fn write_unsupported_test_kind(out: &mut dyn Write, kind: &str) -> io::Result<()> {
    writeln!(out, "    // Unknown test kind: {kind}")?;
    writeln!(
        out,
        "    unimplemented!(\"test kind '{}' not supported\");",
        kind
    )?;

    Ok(())
}

fn escape_string_literal(value: &str) -> String {
    let mut escaped = String::new();

    for ch in value.chars() {
        match ch {
            '\\' => escaped.push_str("\\\\"),
            '"' => escaped.push_str("\\\""),
            '\n' => escaped.push_str("\\n"),
            '\r' => escaped.push_str("\\r"),
            '\t' => escaped.push_str("\\t"),
            other => escaped.push(other),
        }
    }

    escaped
}
