/// Build script: generates Rust test functions from bench/tests.json.
///
/// This makes tests.json the single source of truth for test definitions.
/// Adding a test to tests.json automatically creates a corresponding #[test] fn.
use serde::Deserialize;
use std::fs;
use std::io::Write;
use std::path::Path;

#[derive(Deserialize)]
struct TestEntry {
    name: String,
    level: u32,
    fixture: String,
    kind: String,
    #[serde(default)]
    expected: Option<String>,
    #[serde(default)]
    expected_output: Option<String>,
    #[serde(default)]
    deprecated_after: Option<u32>,
}

const GENERATED_TEST_WRITE_ERROR: &str = "failed to write generated test file";

fn main() {
    let manifest_dir =
        std::env::var("CARGO_MANIFEST_DIR").expect("build.rs requires CARGO_MANIFEST_DIR");
    let tests_json_path = Path::new(&manifest_dir).join("../tests.json");
    let out_dir = std::env::var("OUT_DIR").expect("build.rs requires OUT_DIR");
    let out_path = Path::new(&out_dir).join("tests_generated.rs");

    // Tell cargo to rerun if tests.json changes
    println!("cargo:rerun-if-changed=../tests.json");
    // Also rerun if any fixture changes
    println!("cargo:rerun-if-changed=../fixtures");

    let json = fs::read_to_string(&tests_json_path)
        .unwrap_or_else(|e| panic!("Cannot read {}: {e}", tests_json_path.display()));
    let tests: Vec<TestEntry> =
        serde_json::from_str(&json).unwrap_or_else(|e| panic!("Cannot parse tests.json: {e}"));

    let mut out = fs::File::create(&out_path)
        .unwrap_or_else(|e| panic!("Cannot create {}: {e}", out_path.display()));

    write_header(&mut out, &tests);
    write_optional_helpers(&mut out, &tests);

    // Compute absolute path to fixtures dir for include_str!()
    let fixtures_abs = Path::new(&manifest_dir)
        .join("../fixtures")
        .canonicalize()
        .unwrap_or_else(|e| panic!("Cannot resolve fixtures dir: {e}"));

    // Generate one #[test] fn per entry
    for test in &tests {
        write_test(&mut out, test, &fixtures_abs);
    }
}

fn write_header(out: &mut impl Write, tests: &[TestEntry]) {
    write_line(
        out,
        "// AUTO-GENERATED by build.rs from tests.json — do not edit",
    );
    write_line(
        out,
        format!(
            "// {} tests across {} levels",
            tests.len(),
            distinct_level_count(tests)
        ),
    );
    write_blank_line(out);
    write_line(out, "use crate::scheme::eval_str;");
    write_blank_line(out);
}

fn distinct_level_count(tests: &[TestEntry]) -> usize {
    let mut levels: Vec<u32> = tests.iter().map(|test| test.level).collect();
    levels.sort_unstable();
    levels.dedup();
    levels.len()
}

fn write_optional_helpers(out: &mut impl Write, tests: &[TestEntry]) {
    if tests.iter().any(|test| test.kind == "eval_str_with_output") {
        write_line(out, "#[allow(unused_imports)]");
        write_line(out, "use crate::scheme::eval_str_with_output;");
        write_blank_line(out);
    }

    if tests
        .iter()
        .any(|test| test.kind == "eval_str_err_with_position")
    {
        write_line(out, "fn has_position_info(msg: &str) -> bool {");
        write_line(
            out,
            "    msg.as_bytes().windows(2).any(|w| w[0].is_ascii_digit() && w[1] == b':')",
        );
        write_line(out, "}");
        write_blank_line(out);
    }

    if tests.iter().any(|test| test.deprecated_after.is_some()) {
        write_line(out, "fn current_bench_level() -> u32 {");
        write_line(out, "    match std::env::var(\"BENCH_LEVEL\") {");
        write_line(out, "        Ok(value) => match value.parse() {");
        write_line(out, "            Ok(level) => level,");
        write_line(out, "            Err(_) => u32::MAX,");
        write_line(out, "        },");
        write_line(out, "        Err(_) => u32::MAX,");
        write_line(out, "    }");
        write_line(out, "}");
        write_blank_line(out);
    }
}

fn write_test(out: &mut impl Write, test: &TestEntry, fixtures_abs: &Path) {
    let fn_name = test.name.replace('-', "_");
    let fixture_path = fixtures_abs.join(&test.fixture);
    let fixture_path_str = fixture_path.display().to_string();

    write_line(out, "#[test]");
    write_line(out, format!("fn test_{fn_name}() {{"));

    if let Some(after) = test.deprecated_after {
        write_line(
            out,
            format!("    if current_bench_level() > {after} {{ return; }}"),
        );
    }

    match test.kind.as_str() {
        "eval_str_ok" => write_eval_str_ok(out, test, &fixture_path_str),
        "eval_str_err" => write_eval_str_err(out, test, &fixture_path_str),
        "eval_str_err_with_position" => write_eval_str_err_with_position(out, &fixture_path_str),
        "eval_str_with_output" => write_eval_str_with_output(out, test, &fixture_path_str),
        other => write_unknown_test_kind(out, other),
    }

    write_line(out, "}");
    write_blank_line(out);
}

fn write_eval_str_ok(out: &mut impl Write, test: &TestEntry, fixture_path_str: &str) {
    let expected = test.expected.as_deref().unwrap_or("");
    let escaped = expected.replace('\\', "\\\\").replace('"', "\\\"");
    write_line(out, "    assert_eq!(");
    write_line(
        out,
        format!("        eval_str(include_str!(\"{fixture_path_str}\").trim()),"),
    );
    write_line(out, format!("        Ok(\"{escaped}\".into())"));
    write_line(out, "    );");
}

fn write_eval_str_err(out: &mut impl Write, test: &TestEntry, fixture_path_str: &str) {
    write_line(out, "    assert!(");
    write_line(
        out,
        format!("        eval_str(include_str!(\"{fixture_path_str}\").trim()).is_err(),"),
    );
    write_line(out, format!("        \"expected error for {}\"", test.name));
    write_line(out, "    );");
}

fn write_eval_str_err_with_position(out: &mut impl Write, fixture_path_str: &str) {
    write_line(
        out,
        format!(
            "    let err = eval_str(include_str!(\"{fixture_path_str}\").trim()).unwrap_err();"
        ),
    );
    write_line(out, "    assert!(");
    write_line(out, "        has_position_info(&err.to_string()),");
    write_line(out, "        \"error should contain position info: {err}\"");
    write_line(out, "    );");
}

fn write_eval_str_with_output(out: &mut impl Write, test: &TestEntry, fixture_path_str: &str) {
    let expected_output = test.expected_output.as_deref().unwrap_or("");
    let escaped = expected_output
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n");
    write_line(
        out,
        format!(
            "    let (_, output) = eval_str_with_output(include_str!(\"{fixture_path_str}\").trim()).unwrap();"
        ),
    );
    write_line(out, format!("    assert_eq!(output, \"{escaped}\");"));
}

fn write_unknown_test_kind(out: &mut impl Write, other: &str) {
    write_line(out, format!("    // Unknown test kind: {other}"));
    write_line(
        out,
        format!("    unimplemented!(\"test kind '{other}' not supported\");"),
    );
}

fn write_blank_line(out: &mut impl Write) {
    write_line(out, "");
}

fn write_line(out: &mut impl Write, line: impl std::fmt::Display) {
    writeln!(out, "{line}").expect(GENERATED_TEST_WRITE_ERROR);
}
