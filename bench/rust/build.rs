/// Build script: generates Rust test functions from `bench/tests.json`.
///
/// This keeps `tests.json` as the single source of truth for test definitions.
use serde::Deserialize;
use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const TESTS_JSON_PATH: &str = "../tests.json";
const FIXTURES_DIR: &str = "../fixtures";
const GENERATED_TESTS_FILE: &str = "tests_generated.rs";

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq)]
enum TestKind {
    #[serde(rename = "eval_str_ok")]
    Value,
    #[serde(rename = "eval_str_err")]
    Error,
    #[serde(rename = "eval_str_err_with_position")]
    PositionedError,
    #[serde(rename = "eval_str_with_output")]
    Output,
}

#[derive(Debug, Deserialize)]
struct TestEntry {
    name: String,
    level: u32,
    fixture: String,
    kind: TestKind,
    #[serde(default)]
    expected: Option<String>,
    #[serde(default)]
    expected_output: Option<String>,
    #[serde(default)]
    deprecated_after: Option<u32>,
}

impl TestEntry {
    fn function_name(&self) -> String {
        self.name.replace('-', "_")
    }

    fn fixture_path(&self, fixtures_dir: &Path) -> PathBuf {
        fixtures_dir.join(&self.fixture)
    }
}

#[derive(Debug)]
enum BuildError {
    MissingEnvVar {
        name: &'static str,
        source: env::VarError,
    },
    ReadTestsJson {
        path: PathBuf,
        source: std::io::Error,
    },
    ParseTestsJson {
        path: PathBuf,
        source: serde_json::Error,
    },
    ResolveFixturesDir {
        path: PathBuf,
        source: std::io::Error,
    },
    WriteGeneratedTests {
        path: PathBuf,
        source: std::io::Error,
    },
}

struct BuildPaths {
    tests_json: PathBuf,
    fixtures_dir: PathBuf,
    out_path: PathBuf,
}

impl BuildPaths {
    fn discover() -> Result<Self, BuildError> {
        let manifest_dir = read_env_var("CARGO_MANIFEST_DIR")?;
        let out_dir = read_env_var("OUT_DIR")?;
        let tests_json = Path::new(&manifest_dir).join(TESTS_JSON_PATH);
        let fixtures_path = Path::new(&manifest_dir).join(FIXTURES_DIR);
        let fixtures_dir =
            fixtures_path
                .canonicalize()
                .map_err(|source| BuildError::ResolveFixturesDir {
                    path: fixtures_path,
                    source,
                })?;
        let out_path = Path::new(&out_dir).join(GENERATED_TESTS_FILE);

        Ok(Self {
            tests_json,
            fixtures_dir,
            out_path,
        })
    }
}

fn main() -> Result<(), BuildError> {
    println!("cargo:rerun-if-changed={TESTS_JSON_PATH}");
    println!("cargo:rerun-if-changed={FIXTURES_DIR}");

    let paths = BuildPaths::discover()?;
    let tests = load_tests(&paths.tests_json)?;
    let generated = generate_tests_module(&tests, &paths.fixtures_dir);

    fs::write(&paths.out_path, generated).map_err(|source| BuildError::WriteGeneratedTests {
        path: paths.out_path.clone(),
        source,
    })?;

    Ok(())
}

fn read_env_var(name: &'static str) -> Result<String, BuildError> {
    env::var(name).map_err(|source| BuildError::MissingEnvVar { name, source })
}

fn load_tests(path: &Path) -> Result<Vec<TestEntry>, BuildError> {
    let json = fs::read_to_string(path).map_err(|source| BuildError::ReadTestsJson {
        path: path.to_path_buf(),
        source,
    })?;

    serde_json::from_str(&json).map_err(|source| BuildError::ParseTestsJson {
        path: path.to_path_buf(),
        source,
    })
}

fn generate_tests_module(tests: &[TestEntry], fixtures_dir: &Path) -> String {
    let mut out = CodeWriter::default();

    write_header(&mut out, tests);
    write_helpers(&mut out, tests);

    for test in tests {
        write_test(&mut out, test, fixtures_dir);
    }

    out.finish()
}

fn write_header(out: &mut CodeWriter, tests: &[TestEntry]) {
    out.line("// AUTO-GENERATED by build.rs from tests.json; do not edit");
    out.line(format!(
        "// {} tests across {} levels",
        tests.len(),
        count_levels(tests)
    ));
    out.blank_line();
    out.line("use crate::scheme::eval_str;");
    out.blank_line();
}

fn count_levels(tests: &[TestEntry]) -> usize {
    tests
        .iter()
        .map(|test| test.level)
        .collect::<BTreeSet<_>>()
        .len()
}

fn write_helpers(out: &mut CodeWriter, tests: &[TestEntry]) {
    if tests.iter().any(|test| test.kind == TestKind::Output) {
        out.line("#[allow(unused_imports)]");
        out.line("use crate::scheme::eval_str_with_output;");
        out.blank_line();
    }

    if tests
        .iter()
        .any(|test| test.kind == TestKind::PositionedError)
    {
        out.line("fn has_position_info(msg: &str) -> bool {");
        out.line("    msg.as_bytes()");
        out.line("        .windows(2)");
        out.line("        .any(|window| window[0].is_ascii_digit() && window[1] == b':')");
        out.line("}");
        out.blank_line();
    }

    if tests.iter().any(|test| test.deprecated_after.is_some()) {
        out.line("fn current_bench_level() -> u32 {");
        out.line("    match std::env::var(\"BENCH_LEVEL\") {");
        out.line("        Ok(level) => level");
        out.line("            .parse()");
        out.line("            .expect(\"BENCH_LEVEL should be a valid u32\"),");
        out.line("        Err(_) => u32::MAX,");
        out.line("    }");
        out.line("}");
        out.blank_line();
    }
}

fn write_test(out: &mut CodeWriter, test: &TestEntry, fixtures_dir: &Path) {
    let fixture_expr = include_fixture_expr(&test.fixture_path(fixtures_dir));

    out.line("#[test]");
    out.line(format!("fn test_{}() {{", test.function_name()));

    if let Some(after) = test.deprecated_after {
        out.line(format!("    if current_bench_level() > {after} {{"));
        out.line("        return;");
        out.line("    }");
    }

    match test.kind {
        TestKind::Value => {
            write_eval_str_ok(out, &fixture_expr, test.expected.as_deref().unwrap_or(""))
        }
        TestKind::Error => write_eval_str_err(out, &fixture_expr, &test.name),
        TestKind::PositionedError => write_eval_str_err_with_position(out, &fixture_expr),
        TestKind::Output => write_eval_str_with_output(
            out,
            &fixture_expr,
            test.expected_output.as_deref().unwrap_or(""),
        ),
    }

    out.line("}");
    out.blank_line();
}

fn include_fixture_expr(path: &Path) -> String {
    let fixture_path = rust_string_literal(path.to_string_lossy().as_ref());
    format!("include_str!(\"{fixture_path}\").trim()")
}

fn write_eval_str_ok(out: &mut CodeWriter, fixture_expr: &str, expected: &str) {
    let expected = rust_string_literal(expected);

    out.line("    assert_eq!(");
    out.line(format!("        eval_str({fixture_expr}),"));
    out.line(format!("        Ok(\"{expected}\".into())"));
    out.line("    );");
}

fn write_eval_str_err(out: &mut CodeWriter, fixture_expr: &str, test_name: &str) {
    let message = rust_string_literal(&format!("expected error for {test_name}"));

    out.line("    assert!(");
    out.line(format!("        eval_str({fixture_expr}).is_err(),"));
    out.line(format!("        \"{message}\""));
    out.line("    );");
}

fn write_eval_str_err_with_position(out: &mut CodeWriter, fixture_expr: &str) {
    out.line(format!("    let err = eval_str({fixture_expr})"));
    out.line("        .expect_err(\"expected evaluation to fail\");");
    out.line("    assert!(");
    out.line("        has_position_info(&err.to_string()),");
    out.line("        \"error should contain position info: {err}\"");
    out.line("    );");
}

fn write_eval_str_with_output(out: &mut CodeWriter, fixture_expr: &str, expected_output: &str) {
    let expected_output = rust_string_literal(expected_output);

    out.line(format!(
        "    let (_, output) = eval_str_with_output({fixture_expr})"
    ));
    out.line("        .expect(\"eval_str_with_output should succeed\");");
    out.line(format!("    assert_eq!(output, \"{expected_output}\");"));
}

fn rust_string_literal(text: &str) -> String {
    text.chars().flat_map(char::escape_default).collect()
}

#[derive(Default)]
struct CodeWriter {
    buffer: String,
}

impl CodeWriter {
    fn line<T>(&mut self, line: T)
    where
        T: AsRef<str>,
    {
        self.buffer.push_str(line.as_ref());
        self.buffer.push('\n');
    }

    fn blank_line(&mut self) {
        self.buffer.push('\n');
    }

    fn finish(self) -> String {
        self.buffer
    }
}
